function base(
  partial: Omit<ModerationItem, 'createdAt' | 'updatedAt' | 'version' | 'checklist' | 'relatedReportIds' | 'automatedFlags' | 'previousSnapshot' | 'currentSnapshot' | 'documentStatus' | 'moderatorNote' | 'assignedModeratorId' | 'assignedModeratorName' | 'previousDecisionId' | 'reportsCount' | 'dataOrigin'> &
    Partial<ModerationItem>,
): ModerationItem {
  return {
    assignedModeratorId: null,
    assignedModeratorName: null,
    reportsCount: 0,
    previousDecisionId: null,
    checklist: [],
    relatedReportIds: [],
    automatedFlags: [],
    dataOrigin: DATA_ORIGIN.USER,
    previousSnapshot: null,
    currentSnapshot: null,
    documentStatus: null,
    moderatorNote: null,
    version: 1,
    createdAt: partial.submittedAt,
    updatedAt: partial.submittedAt,
    ...partial,
  }
}

